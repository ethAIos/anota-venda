val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.isFile) {
        file.inputStream().use(::load)
    }
}

fun signingProperty(name: String): String? =
    providers.gradleProperty(name).orNull
        ?: providers.environmentVariable(name).orNull
        ?: localProperties.getProperty(name)

val releaseStoreFile = signingProperty("CADERNINHO_RELEASE_STORE_FILE")
val releaseStorePassword = signingProperty("CADERNINHO_RELEASE_STORE_PASSWORD")
val releaseKeyAlias = signingProperty("CADERNINHO_RELEASE_KEY_ALIAS")
val releaseKeyPassword = signingProperty("CADERNINHO_RELEASE_KEY_PASSWORD")
val hasReleaseSigning = listOf(
    releaseStoreFile,
    releaseStorePassword,
    releaseKeyAlias,
    releaseKeyPassword,
).all { !it.isNullOrBlank() }

